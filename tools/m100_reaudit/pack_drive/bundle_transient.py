"""Package the three *frozen* CMU transient calibration artifacts for Qt/Gazebo."""

import hashlib
import json
from pathlib import Path
import struct
import zlib

import numpy as np


HERE = Path(__file__).resolve().parent
SOURCE = HERE.parents[2] / "results/m100_reaudit/transient_airborne"
FILES = ("model.json", "field_support.npz", "pooled_model.json")
FEATURES = ("speed_mps", "along_accel_mps2", "vertical_up_mps",
            "low_speed_dwell_s", "altitude_agl_m", "tilt_deg")
REGIMES = ("speed_up", "braking", "low_speed_settling", "settling", "nearly_steady_motion")
RANGES = ("speed_mps", "along_accel_mps2", "vertical_up_mps", "tilt_deg",
          "positive_horizontal_work", "braking_horizontal_work_magnitude", "power_w")
COEFFICIENTS = ("horizontal_speed", "horizontal_speed_squared", "signed_vertical_work",
                "positive_horizontal_work", "braking_horizontal_work_magnitude", "sec_tilt_minus_one")


def main():
    hashes = {name: hashlib.sha256((SOURCE / name).read_bytes()).hexdigest() for name in FILES}
    identity = hashlib.sha256("\n".join(f"{name} {digest}" for name, digest in hashes.items()).encode()).hexdigest()
    local = json.loads((SOURCE / FILES[0]).read_text())
    pooled = json.loads((SOURCE / FILES[2]).read_text())
    if (local["schema"] != "CMU_LOCAL_NEAR_LEVEL_AIRCRAFT_PACK_POWER_V1"
            or pooled["schema"] != "CMU_POOLED_NEAR_LEVEL_AIRCRAFT_PACK_POWER_V1"
            or local["support_file"] != FILES[1] or local["support_sha256"] != hashes[FILES[1]]
            or tuple(local["features"]) != FEATURES or tuple(local["regimes"]) != REGIMES):
        raise ValueError("Unrecognized local/pooled calibration release")
    for name in FILES[:2]:
        if pooled["fit_provenance"][f"results/m100_reaudit/transient_airborne/{name}"] != hashes[name]:
            raise ValueError(f"Pooled fit and local release disagree on {name}")
    with np.load(SOURCE / FILES[1], allow_pickle=False) as archive:
        observations = archive["observations"]
    col = local["columns"].index
    if (observations.shape != (pooled["retained_training_points"], len(local["columns"]))
            or not np.isfinite(observations).all()):
        raise ValueError("Invalid frozen donor observations")
    if (set(np.unique(observations[:, col("flight_id")])) != set(pooled["training_contributing_ids"])
            or np.any(observations[:, col("weight_s")] <= 0)
            or np.any(observations[:, col("power_w")] <= 0)):
        raise ValueError("Invalid flight membership, time weights or pack power")
    columns = [col(name) for name in (*FEATURES, "power_w", "weight_s", "flight_id")]
    payloads = []
    for name, support in pooled["payload_support"].items():
        payload = float(name)
        rows = observations[observations[:, col("payload_kg")] == payload]
        groups = []
        for regime in range(len(REGIMES)):
            group = rows[rows[:, col("regime_code")] == regime]
            order = np.argsort(group[:, col("speed_mps")], kind="stable")
            # Same stable speed ordering used by the published local kernel.
            groups.append(group[order][:, columns].tolist())
        if sum(map(len, groups)) != support["retained_training_points"]:
            raise ValueError(f"Donor count differs for payload {name}")
        bands = list(support["actual_agl_m_by_planned_altitude_m"].values())
        if not bands or any(len(band) != 2 or band[1] < band[0] for band in bands):
            raise ValueError(f"Invalid altitude bands for payload {name}")
        payloads.append({
            "kg": payload, "intercept_w": pooled["coefficients"][f"intercept_{name}kg_W"],
            "dwell_limit_s": support["max_observed_slow_level_dwell_s"],
            "ranges": [support["ranges"][key] for key in RANGES],
            "altitude_bands_m": bands,
            "groups": groups,
        })
    model_id = "CMU_TRANSIENT_AIRBORNE_V1:" + identity
    document = {
        "id": model_id, "sources": hashes, "credit": local["source"], "policy": local["policy"],
        "coefficients": [pooled["coefficients"][key] for key in COEFFICIENTS],
        "base_mass_kg": pooled["base_physical_mass_kg"], "gravity_mps2": pooled["gravity_mps2"],
        "payloads": payloads,
    }
    # qUncompress expects a big-endian uncompressed length followed by an RFC 1950 zlib stream.
    encoded = json.dumps(document, separators=(",", ":"), sort_keys=True, allow_nan=False).encode("ascii")
    (HERE / "cmu_transient_v1.qz").write_bytes(struct.pack(">I", len(encoded)) + zlib.compress(encoded, 9))
    (HERE / "M100TransientModelId.hh").write_text(
        "// Generated by bundle_transient.py from the frozen CMU releases.\n"
        "#pragma once\n\nnamespace m100::transient\n{\n"
        f'inline constexpr char kCalibrationId[] = "{model_id}";\n'
        f'inline constexpr char kCalibrationContentSha256[] = "{hashlib.sha256(encoded).hexdigest()}";\n'
        "}\n"
    )


if __name__ == "__main__":
    main()
